export function researchTopicBySlug(slug: string): ResearchTopic | null {
  return researchTopics.find(topic => topic.slug === slug) ?? null;
}
export function matchesResearchTopic(topic: ResearchTopic, query: string): boolean {
  const term = query.trim().toLocaleLowerCase();
  if (!term) return true;
  return [
    topic.code, topic.title, topic.idea, topic.question, topic.trackLabel, topic.decision,
    ...topic.journals.flatMap(id => [id, journalFits[id].name, journalFits[id].category]),
  ].join(' ').toLocaleLowerCase().includes(term);
}
